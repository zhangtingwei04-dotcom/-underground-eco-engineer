import {BrowserGameClock} from '../src/ohm-platform/browser-game-clock.mjs';
let wall=1000000,elapsed=500;
const clock=new BrowserGameClock({wallNow:()=>wall,elapsedNow:()=>elapsed,timeZone:'UTC',driftLimitMs:30000});
const list=[];
const check=(name,pass)=>list.push([name,!!pass]);
check('no time until gameplay',clock.nowMs()===null);
clock.start();
check('captures wall time on start',clock.nowMs()===1000000);
elapsed+=120000;
check('advances with elapsed time',clock.nowMs()===1120000);
check('does not mutate wall clock',wall===1000000);
wall=1120000;
check('no unnecessary resync',clock.recheck().resynced===false);
wall+=60000;
check('resync on wall-clock drift',clock.recheck().resynced===true && clock.nowMs()===1180000);
elapsed+=1000;
check('continues after resync',clock.nowMs()===1181000);
check('snapshot has time context',clock.snapshot().ok===true);
elapsed=0;
check('negative elapsed is recovered',clock.nowMs()===1180000);
for(const [name,pass] of list)console.log((pass?'PASS ':'FAIL ')+name);
if(list.some(x=>!x[1]))process.exitCode=1;
