import {MOTION_MODES,validateMotionProfile,createMotionState,requestMotion,DEMO_MOTION_PROFILE} from '../src/ohm-core/reptile-motion.mjs';
const checks=[];
const check=(name,pass)=>checks.push([name,Boolean(pass)]);
const profile=DEMO_MOTION_PROFILE;
check('supported mode vocabulary',MOTION_MODES.includes('slither')&&MOTION_MODES.includes('climb'));
check('test fixture validates',validateMotionProfile(profile).ok);
check('requires reviewed or unverified evidence status',!validateMotionProfile({...profile,evidenceStatus:'fictional'}).ok);
check('requires rest mode',!validateMotionProfile({...profile,modes:['walk']}).ok);
check('reject duplicate modes',!validateMotionProfile({...profile,modes:['rest','rest']}).ok);
check('reject dangling transition',!validateMotionProfile({...profile,transitions:{...profile.transitions,rest:['swim']}}).ok);
const initial=createMotionState(profile,{individualId:'creature-1'});
check('creates isolated motion state',initial.ok&&initial.state.mode==='rest');
const moved=requestMotion(initial.state,'walk',profile);
check('allowed transition gives event',moved.ok&&moved.events[0].type==='motion_changed');
check('does not mutate source state',initial.state.mode==='rest'&&initial.state.sequence===0);
check('reject disallowed jump',!requestMotion(initial.state,'climb',profile).ok);
check('unknown mode rejected',!requestMotion(initial.state,'fly',profile).ok);
check('stable no-op',requestMotion(initial.state,'rest',profile).events.length===0);
check('reject invalid sequence',!requestMotion({...initial.state,sequence:-1},'walk',profile).ok);
check('reject conflicting species',!requestMotion({...initial.state,speciesId:'other'},'walk',profile).ok);
for(const [name,pass] of checks)console.log((pass?'PASS ':'FAIL ')+name);
if(checks.some(x=>!x[1])&&typeof process!=='undefined')process.exitCode=1;
