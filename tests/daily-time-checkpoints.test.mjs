import {DAILY_CHECKPOINTS,checkDailyTime,millisecondsUntilNextCheckpoint} from '../src/ohm-core/daily-time-checkpoints.mjs';
const checks=[];
const check=(name,result)=>checks.push([name,!!result]);
const dateKey='2026-11-08';
const midnight=dateKey+':midnight',morning=dateKey+':morning',noon=dateKey+':noon';
check('four checkpoints',DAILY_CHECKPOINTS.length===4);
check('midnight at 00:00',checkDailyTime({dateKey,minuteOfDay:0}).due[0].id==='midnight');
check('midnight once',checkDailyTime({dateKey,minuteOfDay:1,processedKeys:[midnight]}).due.length===0);
check('morning at 06:00',checkDailyTime({dateKey,minuteOfDay:360,processedKeys:[midnight]}).due[0].id==='morning');
check('noon at 12:00',checkDailyTime({dateKey,minuteOfDay:720,processedKeys:[midnight,morning]}).due[0].id==='noon');
check('evening at 18:00',checkDailyTime({dateKey,minuteOfDay:1080,processedKeys:[midnight,morning,noon]}).due[0].id==='evening');
check('day change distinct',checkDailyTime({dateKey:'2026-11-09',minuteOfDay:0,processedKeys:[midnight]}).due[0].id==='midnight');
check('invalid minute rejected',!checkDailyTime({dateKey,minuteOfDay:1440}).ok);
check('next 6am boundary',millisecondsUntilNextCheckpoint({minuteOfDay:359,second:0})===60000);
check('next midnight from 18:00',millisecondsUntilNextCheckpoint({minuteOfDay:1080,second:0})===21600000);
check('next midnight from 23:59',millisecondsUntilNextCheckpoint({minuteOfDay:1439,second:0})===60000);
for(const [name,pass] of checks)console.log((pass?'PASS ':'FAIL ')+name);
if(checks.some(x=>!x[1]) && typeof process!=='undefined')process.exitCode=1;
